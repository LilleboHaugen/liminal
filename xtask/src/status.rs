//! The `status` command and the `status-check` step of `ci` (`docs/specs/xtask.md` XTASK-R070 …
//! R072 and the "`status` details").
//!
//! [`generate`] is a pure function of the [`RepoModel`]: it renders `docs/STATUS.md` from task and
//! spec frontmatter, `architecture.toml` and the milestone headings of `docs/ROADMAP.md`. Only
//! [`execute`] writes, and only without `--check` (XTASK-R010).

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::io::Write;
use std::path::Path;

use crate::check;
use crate::check_docs::fields::{is_milestone, is_task_id};
use crate::check_docs::rules::{MATURITIES, TASK_STATUSES};
use crate::cli::{self, CommandError, Exit};
use crate::finding::Finding;
use crate::frontmatter::{self, Frontmatter, Value};
use crate::repo::{self, LoadError, RepoModel, file_name};

/// Command name.
pub(crate) const NAME: &str = "status";

/// Name of the `ci` step that runs `status --check`.
pub(crate) const STEP_NAME: &str = "status-check";

/// The generated file, relative to the repository root.
pub(crate) const PATH: &str = "docs/STATUS.md";

/// Where milestone names come from.
const ROADMAP: &str = "docs/ROADMAP.md";

/// Line 1 of the generated file (XTASK-R071).
const NOTICE: &str =
    "<!-- Generated by `cargo xtask status` (XTASK-R071). Do not edit by hand. -->";

/// The block quote under the title: sources, how to regenerate, where hand-written notes live.
const INTRO: &str = "\
> Generated from task frontmatter (`docs/tasks/`), spec frontmatter (`docs/specs/`),
> `architecture.toml` and the milestone headings in `docs/ROADMAP.md`. Regenerate it with
> `cargo xtask status`; `cargo xtask ci` fails while it is out of date.
> Hand-written notes (prerequisites, owner decisions, context for blockers):
> [STATUS_NOTES.md](STATUS_NOTES.md).
";

/// Task statuses in the column order of the milestone table.
const STATUS_COLUMNS: &[&str] = &["todo", "in-progress", "blocked", "review", "done"];

/// The `status` command as registered in the command table.
pub(crate) fn command(args: &[String], out: &mut dyn Write) -> Result<Exit, CommandError> {
    execute(args, out, &repo::root())
}

/// Runs `status [--check]` on the repository at `root`.
pub(crate) fn execute(
    args: &[String],
    out: &mut dyn Write,
    root: &Path,
) -> Result<Exit, CommandError> {
    let mut check_only = false;
    for arg in args {
        match arg.as_str() {
            "--check" => check_only = true,
            _ => return Err(cli::unexpected_argument(NAME, arg)),
        }
    }
    let model = repo::load(root)?;
    let findings = if check_only {
        check(&model)
    } else {
        match generate(&model) {
            Ok(text) => {
                let message = if model.markdown.get(PATH) == Some(&text) {
                    format!("{NAME}: {PATH} is up to date\n")
                } else {
                    let path = root.join(PATH);
                    std::fs::write(&path, &text)
                        .map_err(|error| CommandError::File { path, error })?;
                    format!("{NAME}: wrote {PATH}\n")
                };
                out.write_all(message.as_bytes())?;
                return Ok(Exit::Success);
            }
            Err(findings) => findings,
        }
    };
    out.write_all(check::human(NAME, &findings).as_bytes())?;
    Ok(if findings.is_empty() {
        Exit::Success
    } else {
        Exit::Failure
    })
}

/// Loads the repository at `root` and runs `status --check` (the [`check::CheckFn`] of the
/// `status-check` step).
///
/// # Errors
///
/// [`LoadError`] if the repository cannot be read into a model.
pub(crate) fn run_check(root: &Path) -> Result<Vec<Finding>, LoadError> {
    Ok(check(&repo::load(root)?))
}

/// The findings of `status --check`: the R070 findings if the input is unreadable, else one
/// XTASK-R072 finding if `docs/STATUS.md` is missing or differs from the generated content.
pub(crate) fn check(model: &RepoModel) -> Vec<Finding> {
    let expected = match generate(model) {
        Ok(text) => text,
        Err(findings) => return findings,
    };
    let help = "Run cargo xtask status and commit docs/STATUS.md";
    match model.markdown.get(PATH) {
        None => vec![Finding::error(
            "XTASK-R072",
            PATH,
            format!("{PATH} does not exist"),
            help,
        )],
        Some(actual) => match first_difference(actual, &expected) {
            None => Vec::new(),
            Some(line) => vec![Finding::error(
                "XTASK-R072",
                format!("{PATH}:{line}"),
                format!("{PATH} differs from the generated content from line {line} on"),
                help,
            )],
        },
    }
}

/// The 1-based number of the first line (with its line ending) that differs, or `None` if the
/// texts are equal.
fn first_difference(actual: &str, expected: &str) -> Option<usize> {
    let mut actual_lines = actual.split_inclusive('\n');
    let mut expected_lines = expected.split_inclusive('\n');
    let mut number = 0;
    loop {
        number += 1;
        match (actual_lines.next(), expected_lines.next()) {
            (None, None) => return None,
            (a, e) if a != e => return Some(number),
            _ => {}
        }
    }
}

/// One task, as far as `status` needs it.
#[derive(Debug)]
struct Task {
    /// Milestone number (`2` for `M2`).
    milestone: u64,
    /// Task number within the milestone (`10` for `M2-T010`).
    number: u64,
    /// `M<n>-T<nnn>`.
    id: String,
    /// The file name inside `docs/tasks/`.
    file: String,
    title: String,
    status: String,
    depends_on: Vec<String>,
}

/// A spec, as far as `status` needs it.
#[derive(Debug)]
struct Spec {
    /// The path relative to the repository root, `docs/specs/<file>`.
    path: String,
    maturity: String,
}

/// Renders `docs/STATUS.md` for `model` (XTASK-R070, R071).
///
/// # Errors
///
/// The XTASK-R070 findings, sorted, if a task or spec file cannot be read for the output.
pub(crate) fn generate(model: &RepoModel) -> Result<String, Vec<Finding>> {
    let mut findings = Vec::new();
    let tasks = tasks(model, &mut findings);
    let specs = specs(model, &mut findings);
    if !findings.is_empty() {
        check::sort(&mut findings);
        return Err(findings);
    }
    let names = milestone_names(model.markdown.get(ROADMAP).map_or("", String::as_str));
    Ok(render(model, &tasks, &specs, &names))
}

/// Reads every task file, sorted by milestone and task number. Unreadable files are reported.
fn tasks(model: &RepoModel, findings: &mut Vec<Finding>) -> Vec<Task> {
    let mut tasks: Vec<Task> = Vec::new();
    let mut paths: BTreeMap<String, String> = BTreeMap::new();
    for (path, text) in model.task_files() {
        match read_task(path, text) {
            Ok(task) => {
                if let Some(first) = paths.get(&task.id) {
                    findings.push(unreadable(
                        path,
                        line_of(text, "id"),
                        &format!("task ID {} is already used by {first}", task.id),
                    ));
                } else {
                    paths.insert(task.id.clone(), path.to_string());
                    tasks.push(task);
                }
            }
            Err((line, message)) => findings.push(unreadable(path, line, &message)),
        }
    }
    tasks.sort_by_key(|task| (task.milestone, task.number));
    tasks
}

/// Reads one task file, or returns the line (if known) and what is wrong.
fn read_task(path: &str, text: &str) -> Result<Task, (Option<usize>, String)> {
    let frontmatter = parse(text)?;
    let (id, id_line) = scalar(&frontmatter, "id")?;
    let (milestone_id, number) =
        id.split_once("-T")
            .filter(|_| is_task_id(id))
            .ok_or_else(|| {
                (
                    Some(id_line),
                    format!("`id` is `{id}`, not a task ID `M<n>-T<nnn>`"),
                )
            })?;
    let (title, _) = scalar(&frontmatter, "title")?;
    let (milestone, milestone_line) = scalar(&frontmatter, "milestone")?;
    if !is_milestone(milestone) || milestone != milestone_id {
        return Err((
            Some(milestone_line),
            format!("`milestone` is `{milestone}`, but the task ID is {id}"),
        ));
    }
    let (status, status_line) = scalar(&frontmatter, "status")?;
    if !TASK_STATUSES.contains(&status) {
        return Err((
            Some(status_line),
            format!(
                "`status` is `{status}`, not one of {}",
                TASK_STATUSES.join(", ")
            ),
        ));
    }
    let depends_on = list(&frontmatter, "depends_on")?;
    let too_large = || {
        (
            Some(id_line),
            format!("task ID {id} has a number too large"),
        )
    };
    Ok(Task {
        milestone: milestone_number(milestone).ok_or_else(too_large)?,
        number: number.parse().map_err(|_| too_large())?,
        id: id.to_string(),
        file: file_name(path).to_string(),
        title: title.to_string(),
        status: status.to_string(),
        depends_on: depends_on.to_vec(),
    })
}

/// Reads every spec file: crate name → spec. Unreadable files are reported. A spec whose
/// `crate` is already named by a spec earlier by path is unreadable too (XTASK-R070), as a task
/// ID used twice is; `check-docs` R022 reports it as a spec whose file name is not `<crate>.md`.
fn specs(model: &RepoModel, findings: &mut Vec<Finding>) -> BTreeMap<String, Spec> {
    let mut specs = BTreeMap::new();
    for (path, text) in model.spec_files() {
        let read = parse(text).and_then(|frontmatter| {
            let (name, crate_line) = scalar(&frontmatter, "crate")?;
            let (maturity, line) = scalar(&frontmatter, "maturity")?;
            if let Some(first) = specs.get(name).map(|spec: &Spec| &spec.path) {
                Err((
                    Some(crate_line),
                    format!("crate `{name}` already has the spec {first}"),
                ))
            } else if MATURITIES.contains(&maturity) {
                Ok((name.to_string(), maturity.to_string()))
            } else {
                Err((
                    Some(line),
                    format!(
                        "`maturity` is `{maturity}`, not one of {}",
                        MATURITIES.join(", ")
                    ),
                ))
            }
        });
        match read {
            Ok((name, maturity)) => {
                specs.insert(
                    name,
                    Spec {
                        path: path.to_string(),
                        maturity,
                    },
                );
            }
            Err((line, message)) => findings.push(unreadable(path, line, &message)),
        }
    }
    specs
}

/// An XTASK-R070 finding: `path` cannot be read for the output.
fn unreadable(path: &str, line: Option<usize>, message: &str) -> Finding {
    let location = match line {
        Some(line) => format!("{path}:{line}"),
        None => path.to_string(),
    };
    Finding::error(
        "XTASK-R070",
        location,
        format!("cannot generate {PATH}: {message}"),
        "Fix the frontmatter; cargo xtask check-docs reports the details",
    )
}

fn parse(text: &str) -> Result<Frontmatter, (Option<usize>, String)> {
    frontmatter::parse(text)
        .map_err(|error| (Some(error.line), format!("frontmatter: {}", error.message)))
}

fn scalar<'a>(
    frontmatter: &'a Frontmatter,
    key: &str,
) -> Result<(&'a str, usize), (Option<usize>, String)> {
    match frontmatter.get(key) {
        None => Err((None, format!("required field `{key}` is missing"))),
        Some(field) => match &field.value {
            Value::Scalar(text) => Ok((text.as_str(), field.line)),
            Value::List(_) => Err((
                Some(field.line),
                format!("`{key}` must be a single value, not a list"),
            )),
        },
    }
}

fn list<'a>(
    frontmatter: &'a Frontmatter,
    key: &str,
) -> Result<&'a [String], (Option<usize>, String)> {
    match frontmatter.get(key) {
        None => Err((None, format!("required field `{key}` is missing"))),
        Some(field) => match &field.value {
            Value::List(items) => Ok(items.as_slice()),
            Value::Scalar(_) => Err((Some(field.line), format!("`{key}` must be a list"))),
        },
    }
}

/// The line of frontmatter field `key` in `text`, if the frontmatter parses and has it.
fn line_of(text: &str, key: &str) -> Option<usize> {
    frontmatter::parse(text)
        .ok()
        .and_then(|frontmatter| frontmatter.get(key).map(|field| field.line))
}

/// `M<n>` → `n`.
fn milestone_number(milestone: &str) -> Option<u64> {
    milestone.strip_prefix('M')?.parse().ok()
}

/// Milestone number → name, from headings `## M<n> — <name>` (the first heading of a milestone
/// wins).
fn milestone_names(roadmap: &str) -> BTreeMap<u64, String> {
    let mut names = BTreeMap::new();
    for line in roadmap.lines() {
        let Some((id, name)) = line
            .strip_prefix("## ")
            .and_then(|rest| rest.split_once(" — "))
        else {
            continue;
        };
        let name = name.trim_end();
        if is_milestone(id)
            && !name.is_empty()
            && let Some(number) = milestone_number(id)
        {
            names.entry(number).or_insert_with(|| name.to_string());
        }
    }
    names
}

/// A table cell: `|` is escaped so the row keeps its columns.
fn cell(text: &str) -> String {
    text.replace('|', "\\|")
}

/// `M<n> (<name>)`, or `M<n>` without a name.
fn milestone_label(number: u64, names: &BTreeMap<u64, String>) -> String {
    match names.get(&number) {
        Some(name) => format!("M{number} ({})", cell(name)),
        None => format!("M{number}"),
    }
}

/// Renders the file (spec "`status` details", Layout). Writing to a `String` cannot fail.
fn render(
    model: &RepoModel,
    tasks: &[Task],
    specs: &BTreeMap<String, Spec>,
    names: &BTreeMap<u64, String>,
) -> String {
    let mut text = format!("{NOTICE}\n# Status\n\n{INTRO}\n## Current milestone\n\n");
    let current = tasks
        .iter()
        .find(|task| task.status != "done")
        .map(|task| task.milestone);
    match current {
        None => text.push_str("No milestone has open tasks.\n"),
        Some(milestone) => {
            let in_milestone: Vec<&Task> =
                tasks.iter().filter(|t| t.milestone == milestone).collect();
            let done = in_milestone.iter().filter(|t| t.status == "done").count();
            let label = match names.get(&milestone) {
                Some(name) => format!("**M{milestone}** ({})", cell(name)),
                None => format!("**M{milestone}**"),
            };
            let _ = writeln!(
                text,
                "{label}: {done} of {} tasks done.\n",
                in_milestone.len()
            );
            text.push_str("| Task | Title | Status | Depends on |\n|---|---|---|---|\n");
            for task in in_milestone {
                let depends = if task.depends_on.is_empty() {
                    "—".to_string()
                } else {
                    cell(&task.depends_on.join(", "))
                };
                let _ = writeln!(
                    text,
                    "| [{}](tasks/{}) | {} | {} | {depends} |",
                    task.id,
                    task.file,
                    cell(&task.title),
                    task.status
                );
            }
        }
    }

    text.push_str("\n## Blocked tasks\n\n");
    let blocked: Vec<&Task> = tasks.iter().filter(|t| t.status == "blocked").collect();
    if blocked.is_empty() {
        text.push_str("None.\n");
    }
    for task in blocked {
        let _ = writeln!(text, "- [{}](tasks/{}): {}", task.id, task.file, task.title);
    }

    text.push_str("\n## Milestones\n\n");
    text.push_str("| Milestone | Tasks | todo | in-progress | blocked | review | done |\n");
    text.push_str("|---|---|---|---|---|---|---|\n");
    let mut milestones: BTreeMap<u64, Vec<&Task>> = BTreeMap::new();
    for task in tasks {
        milestones.entry(task.milestone).or_default().push(task);
    }
    for (number, in_milestone) in &milestones {
        let _ = write!(
            text,
            "| {} | {} |",
            milestone_label(*number, names),
            in_milestone.len()
        );
        for status in STATUS_COLUMNS {
            let count = in_milestone.iter().filter(|t| t.status == *status).count();
            let _ = write!(text, " {count} |");
        }
        text.push('\n');
    }

    text.push_str("\n## Crates\n\n| Crate | Layer | Maturity | Spec |\n|---|---|---|---|\n");
    let mut crates: Vec<_> = model.architecture.crates.iter().collect();
    crates.sort_by(|a, b| (a.layer, &a.name).cmp(&(b.layer, &b.name)));
    for entry in crates {
        let (maturity, spec) = match specs.get(&entry.name) {
            Some(spec) => {
                let file = file_name(&spec.path);
                (spec.maturity.as_str(), format!("[{file}](specs/{file})"))
            }
            None => ("planned", "—".to_string()),
        };
        let _ = writeln!(
            text,
            "| {} | {} | {maturity} | {spec} |",
            cell(&entry.name),
            entry.layer
        );
    }
    text
}

