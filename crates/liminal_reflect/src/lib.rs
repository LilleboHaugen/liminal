//! Runtime reflection for Liminal: engine code inspects and changes values whose concrete type it
//! does not know at compile time.
//!
//! - [`info`]: stable type IDs ([`info::StableTypeId`], XXH64 of the type path) and type
//!   descriptors ([`info::TypeInfo`]).
//! - [`value`]: the object-safe [`value::Reflect`] trait, the static [`value::Typed`] trait, the
//!   access traits and views, field access by name and checked downcasts on `dyn Reflect`, the
//!   consistency check [`value::validate_reflect`], and the hand-written impls for primitives,
//!   `String`, `Vec<T>`, `[T; N]` and `Option<T>`.
//! - [`registry`]: [`registry::TypeRegistry`], descriptors by stable type ID.
//! - [`hash`]: the canonical state encoding of a reflected value ([`hash::write_reflect`]).
//! - [`error`]: [`error::ReflectError`] (`LIM-REFL-NNNN`).
//!
//! Specification: `docs/specs/liminal_reflect.md`.
//!
//! Every public item is public only at its module path (`liminal_reflect::value::Reflect`); the
//! crate root re-exports nothing. The crate has no `unsafe` code and reads no clock, environment
//! or OS randomness (ADR-0009). The derive macro (`liminal_reflect_derive`) is added by M1-T032.
//!
//! # Examples
//!
//! ```
//! use liminal_reflect::hash::reflect_state_hash;
//! use liminal_reflect::info::{Shape, TypeRef};
//! use liminal_reflect::value::{Reflect, Typed};
//!
//! let path: Vec<u16> = vec![3, 4];
//! assert_eq!(<Vec<u16>>::type_path(), "Vec<u16>");
//! assert_eq!(<Vec<u16>>::type_info().shape, Shape::List { element: TypeRef::of::<u16>() });
//!
//! // The same content gives the same hash in every process and on every platform.
//! let value: &dyn Reflect = &path;
//! assert_eq!(reflect_state_hash(value), reflect_state_hash(&vec![3_u16, 4]));
//! ```

#![forbid(unsafe_code)]

