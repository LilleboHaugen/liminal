/// The first `length` bytes of the xxHash sanity test buffer: byte `i` is the top byte of
/// `2654435761 × 11400714785074694797^i mod 2^64`.
pub fn sanity_buffer(length: usize) -> Vec<u8> {
    let mut generator: u64 = 2_654_435_761;
    (0..length)
        .map(|_| {
            let byte = generator.to_be_bytes()[0];
            generator = generator.wrapping_mul(11_400_714_785_074_694_797);
            byte
        })
        .collect()
}

